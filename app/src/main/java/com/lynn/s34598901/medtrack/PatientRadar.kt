/**
 * Screen for Patient Radar.
 *
 * This function:
 * 1. Displays the patient radar data
 * 2. Allows the clinician to filter the data by concern level
 * 3. Allows the clinician to generate a summary of the data
 *
 */
@Composable
fun PatientRadarScreen(
    clinicianViewModel: ClinicianViewModel,
    modifier: Modifier = Modifier
){
    // Store the selected tab and filter
    var selectedTab by remember { mutableStateOf("cards") }
    var selectedFilter by remember { mutableStateOf("All") }

    val radarItems by clinicianViewModel.radarItems.collectAsState()
    val radarSummaryState by clinicianViewModel.radarSummaryState.collectAsState()

    // Load the latest patient radar data when the screen first opens
    LaunchedEffect(Unit){
        clinicianViewModel.loadPatientRadar()
    }

    // Filter the patient radar data based on the selected filter
    val filteredRadarItems = if (selectedFilter == "All"){
        radarItems
    } else {
        radarItems.filter { item ->
            item.concernLevel == selectedFilter }
    }

    Surface(
        modifier = modifier.fillMaxSize(),
        color = Color(0xFFF1F7F6)
    ){
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(16.dp)
        ){
            // Title
            Text(
                text = "Patient Priority Radar",
                fontSize = 28.sp,
                fontWeight = FontWeight.ExtraBold,
                fontFamily = FontFamily.SansSerif,
                textAlign = TextAlign.Center,
                modifier = Modifier.fillMaxWidth()
            )

            Spacer(modifier = Modifier.height(12.dp))

            // Show buttons for switching tabs between overview and ranking
            PatientRadarTabs(
                selectedTab = selectedTab,
                onTabSelected = { selectedTab = it}
            )

            Spacer(modifier = Modifier.height(10.dp))

            // Show filter buttons for concern levels
            PatientRadarFilterButtons(
                selectedFilter = selectedFilter,
                onFilterSelected = { selectedFilter = it }
            )

            Spacer(modifier = Modifier.height(10.dp))

            // Show patient overview cards or priority ranking based on the selected tab
            if (selectedTab == "cards"){
                PatientCardsSection(
                    radarItems = filteredRadarItems
                )
            } else {
                PriorityRankingSection(
                    radarItems = filteredRadarItems
                )
            }

            Spacer(modifier = Modifier.height(10.dp))

            // Show the patient radar summary generated by AI
            PatientRadarGenAI(
                radarSummaryState = radarSummaryState,
                onGenerateSummaryClick = { clinicianViewModel.generateRadarSummary() }
            )
        }
    }
}

/**
 * Show tab buttons for switching between overview and ranking.
 */
@Composable
fun PatientRadarTabs(
    selectedTab: String,
    onTabSelected: (String) -> Unit
){
    // Color used for selected and unselected tabs
    val selectedColor = Color(0xFF232F72)
    val unselectedColor = Color.White

    // Border color used for selected and unselected tabs
    val selectedBorder = Color.White
    val unselectedBorder = Color.Black

    Row(
        modifier = Modifier.fillMaxWidth(),
        horizontalArrangement = Arrangement.spacedBy(8.dp)
    ){

        // Buttons for showing the patient overview cards
        Button(
            onClick = { onTabSelected("cards") },
            modifier = Modifier
                .weight(1f)
                .height(44.dp)
                .border(
                    width = 1.dp,
                    color = if (selectedTab == "cards") selectedBorder else unselectedBorder,
                    shape = RoundedCornerShape(8.dp)
                ),
            shape = RoundedCornerShape(8.dp),
            contentPadding = PaddingValues(horizontal = 20.dp, vertical = 10.dp),
            colors = ButtonDefaults.buttonColors(
                containerColor = if (selectedTab == "cards") selectedColor else unselectedColor,
                contentColor = if (selectedTab == "cards") Color.White else Color.Black
            )
        ){
            Text(
                text = "Overview",
                fontSize = 15.sp,
                fontWeight = FontWeight.Bold,
                maxLines = 1
            )
        }

        // Buttons for showing the patient priority ranking
        Button(
            onClick = {onTabSelected("ranking")},
            modifier = Modifier
                .weight(1f)
                .height(42.dp)
                .border(
                    width = 1.dp,
                    color = if (selectedTab == "ranking") selectedBorder else unselectedBorder,
                    shape = RoundedCornerShape(8.dp)
                ),
            shape = RoundedCornerShape(8.dp),
            contentPadding = PaddingValues(horizontal = 20.dp, vertical = 10.dp),
            colors = ButtonDefaults.buttonColors(
                containerColor = if (selectedTab == "ranking") selectedColor else unselectedColor,
                contentColor = if (selectedTab == "ranking") Color.White else Color.Black
            )
        ){
            Text(
                text = "Priority Ranking",
                fontSize = 15.sp,
                fontWeight = FontWeight.Bold,
                maxLines = 1
            )
        }
    }
    Spacer(modifier = Modifier.height(10.dp))

    // Horizontal divider to separate the tabs from the filter section
    HorizontalDivider()
}

/**
 * Show filter buttons for selecting which concern level to display
 */
@Composable
fun PatientRadarFilterButtons(
    selectedFilter: String,
    onFilterSelected: (String) -> Unit
){
    // List of concern levels to filter by
    val filters = listOf("All", "Urgent", "High", "Moderate", "Low")

    // Color used for selected and unselected filter buttons
    val selectedColor = Color(0xFF005461)
    val unselectedColor = Color.White

    // Border color used for selected and unselected filter buttons
    val selectedBorder = Color.White
    val unselectedBorder = Color.Black

    Column(
        modifier = Modifier.fillMaxWidth()
    ){
        Text(
            text = "Filters: ",
            fontSize = 15.sp,
            fontWeight = FontWeight.Bold
        )

        Spacer(modifier = Modifier.height(10.dp))

        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(5.dp)
        ){
            filters.forEach{ filter ->

                // Button for each concern level
                Button(
                    onClick = { onFilterSelected(filter) },
                    modifier = Modifier
                        .weight(1f)
                        .height(40.dp)
                        .border(
                            width = 1.dp,
                            color = if (selectedFilter == filter) selectedBorder else unselectedBorder,
                            shape = RoundedCornerShape(8.dp)
                        ),
                    shape = RoundedCornerShape(8.dp),
                    contentPadding = PaddingValues(horizontal = 8.dp, vertical = 10.dp),
                    colors = ButtonDefaults.buttonColors(
                        containerColor = if (selectedFilter == filter) selectedColor else unselectedColor,
                        contentColor = if (selectedFilter == filter) Color.White else Color.Black
                    ),
                    elevation = ButtonDefaults.buttonElevation(
                        defaultElevation = 0.dp,
                        pressedElevation = 0.dp
                    )
                ){
                    Text(
                        text = filter,
                        fontSize = 13.sp,
                        maxLines = 1
                    )
                }
            }
        }
    }
}

/**
 * Shows patient radar cards for the filtered patients.
 */
@Composable
fun PatientCardsSection(
    radarItems: List<PatientRadarItem>
){
    if (radarItems.isEmpty()){
        Card(
            modifier = Modifier.fillMaxSize(),
            shape = RoundedCornerShape(16.dp)
        ) {

            // Show an empty message when no patients match the current filter
            Text(
                text = "No patient radar data available for this filter",
                modifier = Modifier
                    .padding(16.dp)
                    .background(Color.White)
                    .padding(16.dp),
                color = Color.Gray
            )
        }
    } else{

        // Show each patient radar item as a card
        LazyColumn(
            modifier = Modifier.fillMaxSize()
        ){
            items(radarItems.size){ index ->
                PatientRadarCard(radarItem = radarItems[index])
            }
        }
    }
}


/**
 * Show one patient priority card.
 */
@Composable
fun PatientRadarCard(
    radarItem: PatientRadarItem
){
    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(16.dp)
    ){
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .background(Color.White)
                .padding(16.dp)
        ){
            // Display the patient's name
            Text(
                text = radarItem.patientName,
                fontSize = 18.sp,
                fontWeight = FontWeight.Bold
            )

            // Display the patient's ID
            Text(
                text = "Patient ID: ${radarItem.patientId}",
                fontSize = 14.sp,
                color = Color.Gray
            )

            Spacer(modifier = Modifier.height(10.dp))

            // Show the medication burden score bar
            ScoreBar(
                label = "Medication Burden",
                score = radarItem.medicationScore,
                maxScore = 30
            )

            // Show the symptom severity score bar
            ScoreBar(
                label = "Symptom Severity",
                score = radarItem.severityScore,
                maxScore = 40
            )

            // Show the symptom frequency score bar
            ScoreBar(
                label = "Symptom Frequency",
                score = radarItem.symptomFrequencyScore,
                maxScore = 30
            )

            Spacer(modifier = Modifier.height(8.dp))

            // Show the patient's concern level and priority score
            Text(
                text = "${radarItem.concernLevel} concern -  ${radarItem.concernPercentage}% priority score",
                fontWeight = FontWeight.Bold,
            )

            Spacer(modifier = Modifier.height(6.dp))

            // Display the number of medications, symptoms, and average severity
            Text(
                text = "Medications: ${radarItem.medicationCount} | Symptoms: ${radarItem.symptomCount} | Avg Severity: %.2f".format(radarItem.averageSeverity),
                fontSize = 14.sp
            )

            Spacer(modifier = Modifier.height(6.dp))

            // Display the reason for the patient's priority level
            Text(
                text = "Reason: ${radarItem.reason}",
                fontSize = 14.sp,
                color = Color.DarkGray
            )

            Spacer(modifier = Modifier.height(5.dp))
        }
    }

    Spacer(modifier = Modifier.height(15.dp))
}

/**
 * Show a score bar for a patient radar item.
 * The score is converted into a fraction using maxScore before filling the bar.
 */
@Composable
fun ScoreBar(
    label: String,
    score: Int,
    maxScore: Int
){
    // Convert the score into 0 to 1 fraction for the progress bar width
    val fraction = if (maxScore == 0){
        0f
    } else {
        (score.toFloat() / maxScore).coerceIn(0f, 1f)
    }

    Column {
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.SpaceBetween
        ) {
            // Display the score label
            Text(
                text = label,
                fontSize = 14.sp
            )

            // Display the raw score as a percentage
            Text(
                text = "$score / $maxScore",
                fontSize = 14.sp
            )
        }

        Spacer(modifier = Modifier.height(4.dp))

        // Show the concern score as a horizontal progress indicator
        LinearProgressIndicator(
            progress = { fraction },
            modifier = Modifier
                .fillMaxWidth()
                .height(20.dp),
            color = Color(0xFF2D5F8B),
            trackColor = Color(0xFFEDEDED)
        )

        Spacer(modifier = Modifier.height(8.dp))
    }
}

/**
 * Show patients in ranked order based on overall concern score.
 */
@Composable
fun PriorityRankingSection(
    radarItems: List<PatientRadarItem>
){
    Card(
        modifier = Modifier
            .fillMaxWidth()
            .height(300.dp),
        shape = RoundedCornerShape(16.dp)
    ) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .background(Color.White)
                .padding(16.dp)
        ){
            Text(
                text = "Ranked by Overall Concern Score",
                fontSize = 16.sp,
                fontWeight = FontWeight.Bold
            )

            Spacer(modifier = Modifier.height(10.dp))

            if (radarItems.isEmpty()){

                // SHow an empty message when no patients match the current filter
                Text(
                    text = "No patient radar data available for this filter",
                    color = Color.Gray
                )
            } else {

                // Use 100 as the maximum overall concern score
                val maxScore = 100

                // Show each patient as one ranked row
                LazyColumn{
                    items(radarItems.size){ index ->
                        val item = radarItems[index]

                        PriorityRankingRow(
                            rank = index + 1,
                            item = item,
                            maxScore = maxScore
                        )

                        Spacer(modifier = Modifier.height(10.dp))
                    }
                }
            }
        }
    }
}

/**
 * Show one patient row in the priority ranking list
 */
@Composable
fun PriorityRankingRow(
    rank: Int,
    item: PatientRadarItem,
    maxScore: Int
) {
    // Convert the concern percentage into a fraction for the progress bar width
    val fraction = if (maxScore == 0) {
        0f
    } else {
        item.concernPercentage.toFloat() / maxScore.toFloat()
    }

    Column(
        modifier = Modifier
            .fillMaxWidth()
            .padding(vertical = 8.dp)
    ) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {

            // Rank number
            Text(
                text = "$rank.",
                fontSize = 13.sp,
                fontWeight = FontWeight.Bold,
                modifier = Modifier.weight(0.3f)
            )

            // Patient's name
            Text(
                text = item.patientName,
                fontSize = 13.sp,
                fontWeight = FontWeight.Bold,
                modifier = Modifier.weight(1.4f)
            )

            // Overall concern score
            Text(
                text = "Score ${item.concernPercentage}",
                fontSize = 12.sp,
                textAlign = TextAlign.End,
                modifier = Modifier.weight(0.9f)
            )
        }

        Spacer(modifier = Modifier.height(5.dp))

        // Show the concern score as a horizontal progress indicator
        LinearProgressIndicator(
            progress = { fraction },
            modifier = Modifier
                .fillMaxWidth()
                .height(20.dp),
            color = Color(0xFF2D5F8B),
            trackColor = Color(0xFFEDEDED)
        )

        Spacer(modifier = Modifier.height(5.dp))

        // Patient's concern level
        Text(
            text = item.concernLevel,
            fontSize = 12.sp,
            fontWeight = FontWeight.Bold,
            color = Color(0xFF2D5F8B)
        )
    }
}

/**
 * Show the GenAI radar summary card
 */
@Composable
fun PatientRadarGenAI(
    radarSummaryState: PatientRadarUIState,
    onGenerateSummaryClick: () -> Unit
){
    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(16.dp)
    ){
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .background(Color.White)
                .padding(16.dp)
        ){
            Text(
                text = "Generate Radar Summary",
                fontSize = 20.sp,
                fontWeight = FontWeight.ExtraBold,
                fontFamily = FontFamily.SansSerif
            )

            Spacer(modifier = Modifier.height(10.dp))

            // Start AI summary generation when clicked
            Button(
                onClick = onGenerateSummaryClick,
                modifier = Modifier.fillMaxWidth()
            ){
                Text(
                    text = "Generate Summary",
                    fontSize = 16.sp
                )
            }

            Spacer(modifier = Modifier.height(10.dp))

            // Show the AI generated summary
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(400.dp),
                contentAlignment = Alignment.TopStart
            ){
                when (radarSummaryState){

                    // Show instruction text before the user clicks the button
                    PatientRadarUIState.Initial -> {
                        Text(
                            text = "Generate a short summary of the data.",
                            textAlign = TextAlign.Center,
                            color = Color.Gray
                        )
                    }

                    // Show loading indicator while the AI is generating the summary
                    PatientRadarUIState.Loading -> {
                        CircularProgressIndicator(
                            modifier = Modifier.align(Alignment.Center)
                        )
                    }

                    // Show the AI generated summary
                    is PatientRadarUIState.Success -> {
                        LazyColumn(
                            modifier = Modifier.fillMaxSize()
                        ) {
                            item{
                                Text(
                                    text = radarSummaryState.content,
                                    textAlign = TextAlign.Start
                                )
                            }
                        }
                    }

                    // Show error message if the AI fails to generate the summary
                    is PatientRadarUIState.Error -> {
                        Text(
                            text = "Error: ${radarSummaryState.errorMessage}",
                            color = MaterialTheme.colorScheme.error
                        )
                    }
                }
            }
        }
    }
}

